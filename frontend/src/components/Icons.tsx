export type AgentGlyphName =
  | "inbox"
  | "clipboard"
  | "gauge"
  | "sparkles"
  | "scale"
  | "scroll"

export function AgentGlyph({
  name,
  ...props
}: IconProps & { name: AgentGlyphName }) {
  switch (name) {
    case "inbox":
      return <InboxIcon {...props} />
    case "clipboard":
      return <ClipboardCheckIcon {...props} />
    case "gauge":
      return <GaugeIcon {...props} />
    case "sparkles":
      return <SparklesIcon {...props} />
    case "scale":
      return <ScaleIcon {...props} />
    case "scroll":
      return <ScrollTextIcon {...props} />
  }
}
